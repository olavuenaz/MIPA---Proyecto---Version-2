import yaml
import logging
import numpy as np
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity
from typing import List, Dict, Any

# Initialize logging
logger = logging.getLogger(__name__)

class EvaluationModule:
    """
    Evaluation and Reflection Module.
    
    Verifies relevance and grounding for all generated responses to prevent hallucinations 
    and ensure context alignment.
    """
    
    def __init__(self, config_path: str = "config.yaml"):
        """
        Initializes the EvaluationModule with thresholds from the configuration file.
        
        Args:
            config_path (str): Path to the YAML configuration file.
        """
        with open(config_path, 'r', encoding='utf-8') as f:
            self.config = yaml.safe_load(f)
            
        self.model = SentenceTransformer('all-MiniLM-L6-v2')
        self.rel_threshold = self.config.get("thresholds", {}).get("relevance_min", 0.30)
        self.gnd_threshold = self.config.get("thresholds", {}).get("grounding_min", 0.30)
        
        logger.info("Evaluation module initialized successfully (bypass disabled).")

    def verify_response(self, user_input: str, generated_text: str, context_list: List[str]) -> Dict[str, Any]:
        """
        Evaluates the generated response for relevance against the user input and grounding 
        against the provided context.

        Args:
            user_input (str): The original prompt provided by the user.
            generated_text (str): The text generated by the LLM.
            context_list (List[str]): Retrieved context fragments from memory/RAG.

        Returns:
            Dict[str, Any]: Evaluation payload containing the verification status, 
                            reasoning, and computed metrics (relevance and grounding).
        """
        if not generated_text or len(generated_text.strip()) < 3:
            return {"passed": False, "reason": "Empty or excessively short response"}

        try:
            vec_input = self.model.encode([user_input])
            vec_resp = self.model.encode([generated_text])

            relevance = float(cosine_similarity(vec_input, vec_resp)[0][0])
            grounding = 1.0

            if context_list:
                context_text = " ".join(context_list)
                if len(context_text) > 20:
                    vec_context = self.model.encode([context_text])
                    grounding = float(cosine_similarity(vec_resp, vec_context)[0][0])

            if relevance < self.rel_threshold:
                return {
                    "passed": False,
                    "reason": f"Low relevance ({relevance:.2f} < {self.rel_threshold})",
                    "metrics": {"relevance": relevance, "grounding": grounding}
                }
                
            if context_list and grounding < self.gnd_threshold:
                return {
                    "passed": False,
                    "reason": f"Potential hallucination: low grounding ({grounding:.2f} < {self.gnd_threshold})",
                    "metrics": {"relevance": relevance, "grounding": grounding}
                }

            return {
                "passed": True,
                "reason": "OK",
                "metrics": {"relevance": relevance, "grounding": grounding}
            }

        except Exception as e:
            logger.error("Critical error during response evaluation: %s", str(e))
            # Fallback constraint: return True to prevent halting the system if the evaluator crashes
            return {"passed": True, "reason": "Evaluation module error bypassed"}