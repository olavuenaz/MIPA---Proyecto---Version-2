import csv
import os
import logging
from datetime import datetime
from typing import Dict, Any

# Initialize the module-level logger
logger = logging.getLogger(__name__)

class AuditModule:
    """
    Audit and Logging Module (IEEE 7001 compliance).
    
    Records the reasoning chain for forensic traceability and system auditing.
    """
    
    def __init__(self, logs_dir: str = "./data_memory/logs"):
        """
        Initializes the AuditModule and ensures the log directory exists.
        
        Args:
            logs_dir (str): Path to the directory where logs will be stored.
        """
        self.logs_dir = logs_dir
        os.makedirs(self.logs_dir, exist_ok=True)

    def log_interaction(self, meta: Dict[str, Any], payload: Dict[str, Any], response_text: str) -> None:
        """
        Saves the interaction tuple (Input, Perception, Decision, Action) to a user-specific CSV file.

        Args:
            meta (Dict[str, Any]): Metadata containing at least the 'user_id'.
            payload (Dict[str, Any]): The processing payload containing 'input_text', 'archetype', 'emotion', and 'reason'.
            response_text (str): The final text generated by the system.
        """
        user_id = meta.get("user_id", "anon")
        safe_id = "".join([c for c in user_id if c.isalnum()])
        filepath = os.path.join(self.logs_dir, f"log_{safe_id}.csv")
        
        timestamp = datetime.now().isoformat()
        
        row_data = [
            timestamp,
            payload.get("input_text", ""),
            payload.get("archetype", "UNKNOWN"),
            payload.get("emotion", "Neutral"),
            payload.get("reason", "N/A"),
            response_text
        ]
        
        try:
            file_exists = os.path.exists(filepath)
            with open(filepath, 'a', newline='', encoding='utf-8') as f:
                writer = csv.writer(f)
                if not file_exists:
                    writer.writerow(["Timestamp", "Input", "Archetype", "Emotion", "Reasoning", "Response"])
                writer.writerow(row_data)
        except IOError as e:
            logger.error("Critical audit error (Write failure) for user %s: %s", safe_id, e)